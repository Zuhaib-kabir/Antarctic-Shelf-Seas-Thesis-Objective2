def circular_boundary():
    theta = np.linspace(0.0, 2.0 * np.pi, 361)
    vertices = (
        np.vstack([np.sin(theta), np.cos(theta)]).T
        * 0.5
        + np.array([0.5, 0.5])
    )
    return MplPath(vertices)


