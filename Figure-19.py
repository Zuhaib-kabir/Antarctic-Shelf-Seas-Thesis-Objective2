# 11. HEATMAP DRAWING
def draw_heatmap_panel(
    figure,
    cell,
    matrix,
    symbols,
    column_labels,
    panel_title,
    colorbar_label,
    cmap,
    norm,
    cell_font_size=FONT_CELL,
    title_height=5.1,
    title_y=0.58,
):
    """
    Draw one heatmap using three completely separate vertical bands:

    1. panel title;
    2. variable labels + heatmap;
    3. horizontal colorbar.

    The enlarged title band prevents the panel title from touching the
    variable labels at the top of the heatmap.
    """
    sub = cell.subgridspec(
        3,
        1,
        height_ratios=[title_height, 18.7, 1.35],
        hspace=0.15,
    )

    ax_title = figure.add_subplot(sub[0, 0])
    ax_main = figure.add_subplot(sub[1, 0])
    ax_cbar = figure.add_subplot(sub[2, 0])

    ax_title.set_axis_off()
    ax_title.text(
        0.5,
        title_y,
        panel_title,
        ha="center",
        va="center",
        fontsize=FONT_PANEL_TITLE,
        fontweight="bold",
        linespacing=1.08,
        clip_on=False,
    )

    img = ax_main.imshow(
        matrix,
        cmap=cmap,
        norm=norm,
        aspect="auto",
        interpolation="nearest",
    )

    ax_main.set_xticks(np.arange(len(column_labels)))
    ax_main.set_xticklabels(
        column_labels,
        fontsize=FONT_COLUMN,
        fontweight="bold",
        linespacing=0.98,
    )
    ax_main.xaxis.tick_top()
    ax_main.tick_params(
        axis="x",
        top=True,
        labeltop=True,
        bottom=False,
        labelbottom=False,
        length=0,
        pad=1.5,
    )

    ax_main.set_yticks(np.arange(len(SEA_ORDER)))
    ax_main.set_yticklabels(
        SEA_ORDER,
        fontsize=FONT_TICK,
        fontweight="bold",
    )
    ax_main.tick_params(axis="y", length=0, pad=2.0)

    ax_main.set_xticks(np.arange(-0.5, len(column_labels), 1), minor=True)
    ax_main.set_yticks(np.arange(-0.5, len(SEA_ORDER), 1), minor=True)
    ax_main.grid(which="minor", color="white", linewidth=0.95)
    ax_main.tick_params(which="minor", bottom=False, left=False)

    for i in range(matrix.shape[0]):
        for j in range(matrix.shape[1]):
            value = matrix[i, j]
            if not np.isfinite(value):
                continue

            ax_main.text(
                j,
                i,
                f"{value:.2f}{symbols[i, j]}",
                ha="center",
                va="center",
                fontsize=cell_font_size,
                fontweight="bold",
                color="black",
                clip_on=True,
            )

    cbar = figure.colorbar(
        img,
        cax=ax_cbar,
        orientation="horizontal",
    )
    cbar.set_ticks([-1.0, -0.5, 0.0, 0.5, 1.0])
    cbar.ax.tick_params(labelsize=FONT_TICK, length=2.5, pad=1.2)

    for tick_label in cbar.ax.get_xticklabels():
        tick_label.set_fontweight("bold")

    cbar.set_label(
        colorbar_label,
        fontsize=FONT_AXIS,
        fontweight="bold",
        labelpad=2.0,
    )

    return ax_main


