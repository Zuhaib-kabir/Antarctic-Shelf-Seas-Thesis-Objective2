def draw_composite_panel(
    figure,
    cell,
    composite_field,
    significance_field,
    gebco_field,
    positive_count,
    negative_count,
):
    outer = cell.subgridspec(
        2,
        1,
        height_ratios=[4.8, 18.4],
        hspace=0.04,
    )

    ax_title = figure.add_subplot(outer[0, 0])
    ax_title.axis("off")
    ax_title.text(
        0.5,
        0.66,
        "(h) Positive-minus-negative AAO\nSLA composite",
        ha="center",
        va="center",
        fontsize=FONT_PANEL_TITLE,
        fontweight="bold",
        linespacing=1.02,
        clip_on=False,
    )

    lower = outer[1, 0].subgridspec(
        1,
        4,
        width_ratios=[2.6, 20.8, 1.55, 2.6],
        wspace=0.22,
    )

    proj = ccrs.SouthPolarStereo()
    ax_map = figure.add_subplot(lower[0, 1], projection=proj)
    ax_cbar = figure.add_subplot(lower[0, 2])

    # Center the map–colorbar bundle within the whole panel.
    ax_map.set_anchor("C")
    ax_cbar.set_anchor("W")

    ax_map.set_extent([LON_MIN, LON_MAX, LAT_MIN, LAT_MAX], crs=ccrs.PlateCarree())
    ax_map.set_boundary(circular_boundary(), transform=ax_map.transAxes)

    ax_map.gridlines(
        crs=ccrs.PlateCarree(),
        draw_labels=False,
        xlocs=np.arange(-180, 181, 30),
        ylocs=[-60, -75],
        linewidth=0.45,
        linestyle=":",
        color="0.58",
        alpha=0.75,
        zorder=2,
    )

    finite = np.abs(composite_field.values[np.isfinite(composite_field.values)])
    if finite.size:
        vmax = float(np.nanpercentile(finite, 98.0))
    else:
        vmax = 1.0
    vmax = max(0.5, np.ceil(vmax * 2.0) / 2.0)

    norm = mcolors.TwoSlopeNorm(vmin=-vmax, vcenter=0.0, vmax=vmax)

    img = ax_map.pcolormesh(
        composite_field["lon"].values,
        composite_field["lat"].values,
        composite_field.values,
        transform=ccrs.PlateCarree(),
        cmap="RdBu_r",
        norm=norm,
        shading="auto",
        zorder=4,
    )

    gebco_lon_2d, gebco_lat_2d = np.meshgrid(
        gebco_field["lon"].values,
        gebco_field["lat"].values,
    )

    elev = gebco_field.values
    land = np.where(elev >= 0.0, 1.0, np.nan)

    ax_map.contourf(
        gebco_lon_2d,
        gebco_lat_2d,
        land,
        levels=[0.5, 1.5],
        colors=["0.84"],
        transform=ccrs.PlateCarree(),
        zorder=8,
    )

    ax_map.contour(
        gebco_lon_2d,
        gebco_lat_2d,
        elev,
        levels=[0.0],
        colors="0.30",
        linewidths=0.58,
        transform=ccrs.PlateCarree(),
        zorder=10,
    )

    add_sector_boundaries(ax_map)
    add_map_labels(ax_map)

    sigmask = significance_field.values.astype(bool)
    if sigmask.any():
        lon2d, lat2d = np.meshgrid(
            significance_field["lon"].values,
            significance_field["lat"].values,
        )

        sig_count = int(sigmask.sum())
        stride = max(1, int(np.ceil(np.sqrt(sig_count / 4200.0))))

        mask_sub = sigmask[::stride, ::stride]
        lon_sub = lon2d[::stride, ::stride]
        lat_sub = lat2d[::stride, ::stride]

        rr, cc = np.where(mask_sub)
        ax_map.scatter(
            lon_sub[rr, cc],
            lat_sub[rr, cc],
            transform=ccrs.PlateCarree(),
            s=1.4,
            marker="o",
            facecolor="black",
            edgecolor="none",
            alpha=0.66,
            zorder=12,
        )

    ax_map.text(
        0.03,
        0.035,
        f"AAO+ n={positive_count}\nAAO− n={negative_count}",
        transform=ax_map.transAxes,
        ha="left",
        va="bottom",
        fontsize=FONT_STATS_BOX,
        fontweight="bold",
        bbox=dict(
            boxstyle="round,pad=0.22",
            facecolor="white",
            edgecolor="0.42",
            alpha=0.96,
        ),
        zorder=35,
    )

    cbar = figure.colorbar(
        img,
        cax=ax_cbar,
        orientation="vertical",
        extend="both",
    )
    cbar.set_ticks(np.linspace(-vmax, vmax, 5))
    cbar.ax.tick_params(labelsize=FONT_TICK, length=2.8, pad=2.0)

    for t in cbar.ax.get_yticklabels():
        t.set_fontweight("bold")

    cbar.set_label(
        "SLA composite (cm)",
        fontsize=FONT_AXIS,
        fontweight="bold",
        rotation=90,
        labelpad=8.0,
    )


