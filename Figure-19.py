def table_to_matrix(table, categories, value_column, category_column):
    values = np.full((len(SEA_ORDER), len(categories)), np.nan, dtype=float)
    symbols = np.full((len(SEA_ORDER), len(categories)), "", dtype=object)

    sea_lookup = {sea: i for i, sea in enumerate(SEA_ORDER)}
    category_lookup = {category: i for i, category in enumerate(categories)}

    for _, row in table.iterrows():
        sea = row["sea"]
        category = row[category_column]

        if sea not in sea_lookup or category not in category_lookup:
            continue

        i = sea_lookup[sea]
        j = category_lookup[category]
        values[i, j] = row[value_column]
        symbols[i, j] = row["sig"]

    return values, symbols


matrix_a, symbols_a = table_to_matrix(panel_a, PANEL_A_COLUMNS, "r", "driver")
